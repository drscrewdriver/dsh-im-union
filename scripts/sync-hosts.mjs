/**
 * sync-hosts.mjs —— 从 hosts.mjs（唯一事实源）下发本仓全部宿主声明写点。
 *
 * 机制移植自 dsh-tidy-display/scripts/sync-hosts.mjs（P0 试点定型版），本仓差异：
 * 1. 版本正则放行 rc 与 alpha（0.2.1 线只有 alpha）；
 * 2. 写点 1 = package.json：engines.dsh + 6 个 dsh-* peer（全量枚举，optional——
 *    profile 安装 autoInstallPeers:false，peer 不经注册表解析；树内一旦存在但版本
 *    不在枚举，npm/pnpm 照样 ERESOLVE）+ cordis/schemastery peer（独立版本空间）；
 *    react 为上游生态 peer，本脚本不碰。
 * 3. 写点 2 = dsh.plugin.json：engines.dsh + version 以 package.json 为准镜像；
 * 4. 写点 3 = README.md（简体中文）/ README.en.md 的 host-compat 管理块。
 *
 * 双模式：默认只校验（exit 1 = 有漂移）；`--write` 实际写盘。
 * 用法：node scripts/sync-hosts.mjs [--write]
 */
import { readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import assert from 'node:assert/strict'
import { supportedHosts, peerRange, developmentHost, hostPeerPackages, cordisRange, schemasteryRange } from './hosts.mjs'

const ROOT = new URL('..', import.meta.url)
const write = process.argv.includes('--write')
const read = (rel) => readFile(new URL(rel, ROOT), 'utf8')

// ── 0. hosts.mjs 自检 ────────────────────────────────────────────────────────
const TAG_RE = /^\d+\.\d+\.\d+-(rc|alpha)\.\d+$/
assert(supportedHosts.length > 0, 'supportedHosts 不得为空')
assert.equal(new Set(supportedHosts).size, supportedHosts.length, 'supportedHosts 有重复项')
for (const v of supportedHosts) assert(TAG_RE.test(v), `非 rc/alpha 版本混入枚举: ${v}`)
assert(supportedHosts.includes(developmentHost), 'developmentHost 必须在 supportedHosts 内')
assert(hostPeerPackages.length > 0, 'hostPeerPackages 不得为空')

// ── 1. package.json：engines.dsh + 6 个 dsh-* peer + cordis/schemastery ──────
const pkgUrl = new URL('package.json', ROOT)
const pkgOriginal = await read('package.json')
const pkg = JSON.parse(pkgOriginal)
pkg.engines ??= {}
pkg.engines.dsh = peerRange
pkg.peerDependencies ??= {}
pkg.peerDependenciesMeta ??= {}
for (const name of hostPeerPackages) {
  pkg.peerDependencies[name] = peerRange
  pkg.peerDependenciesMeta[name] = { optional: true }
}
pkg.peerDependencies['@deepseek-ai/cordis'] = cordisRange
pkg.peerDependencies['@deepseek-ai/schemastery'] = schemasteryRange
delete pkg.peerDependenciesMeta['@deepseek-ai/cordis']
delete pkg.peerDependenciesMeta['@deepseek-ai/schemastery']
const pkgExpected = JSON.stringify(pkg, null, 2) + '\n'

// ── 2. dsh.plugin.json：engines.dsh + version 镜像（package.json 为准）────────
const pluginJsonUrl = new URL('dsh.plugin.json', ROOT)
const hasManifest = existsSync(pluginJsonUrl)
let manifestOriginal, manifestExpected
if (hasManifest) {
  manifestOriginal = await read('dsh.plugin.json')
  const manifest = JSON.parse(manifestOriginal)
  manifest.engines ??= {}
  manifest.engines.dsh = peerRange
  manifest.version = pkg.version
  manifestExpected = JSON.stringify(manifest, null, 2) + '\n'
}

// ── 3. README 管理块 ─────────────────────────────────────────────────────────
const BEGIN = '<!-- host-compat:begin — generated by scripts/sync-hosts.mjs from scripts/hosts.mjs; DO NOT EDIT -->'
const END = '<!-- host-compat:end -->'
const versionList = supportedHosts.map((v) => `\`${v}\``).join(' ')
const LINES = '0.1.2 / 0.1.5 / 0.1.7 / 0.2.0 / 0.2.1'
const linesPerLang = {
  'README.md': [
    `- **支持的 DSH 宿主：** ${versionList}（覆盖 ${LINES} 共 ${supportedHosts.length} 个 rc/alpha）`,
  ],
  'README.en.md': [
    `- **Supported DSH hosts:** ${versionList} (${supportedHosts.length} rc/alpha releases across lines ${LINES})`,
  ],
}
// 矩阵跑绿清单（.compat-results/verified.json，由逐线矩阵脚本写出；不存在则不加行）
const verifiedUrl = new URL('.compat-results/verified.json', ROOT)
if (existsSync(verifiedUrl)) {
  const { verified = [] } = JSON.parse(await readFile(verifiedUrl, 'utf8'))
  if (verified.length > 0) {
    const list = verified.map((v) => `\`${v}\``).join(', ')
    linesPerLang['README.md'].push(`- **运行时已验证：** ${list}（证据见 \`.compat-results/\`）`)
    linesPerLang['README.en.md'].push(`- **Runtime-verified:** ${list} — evidence in \`.compat-results/\``)
  }
}
const readmeProblems = []
for (const [file, lines] of Object.entries(linesPerLang)) {
  const block = `${BEGIN}\n${lines.join('\n')}\n${END}`
  const url = new URL(file, ROOT)
  if (!existsSync(url)) {
    readmeProblems.push(`${file} 不存在`)
    continue
  }
  const content = await readFile(url, 'utf8')
  const beginAt = content.indexOf(BEGIN)
  if (beginAt === -1) {
    const at = content.search(/^## /m)
    assert(at !== -1, `${file} 找不到插入锚点（第一个二级标题）`)
    if (write) {
      await writeFile(url, content.slice(0, at) + block + '\n\n' + content.slice(at))
      console.log(`write  ${file}: 插入管理块`)
    } else {
      readmeProblems.push(`${file} 缺少 host-compat 管理块`)
    }
    continue
  }
  const endAt = content.indexOf(END, beginAt)
  assert(endAt !== -1, `${file} 管理块缺少 end 标记`)
  const current = content.slice(beginAt, endAt + END.length)
  if (write) {
    if (current !== block) {
      await writeFile(url, content.slice(0, beginAt) + block + content.slice(endAt + END.length))
      console.log(`write  ${file}: 更新管理块`)
    } else console.log(`ok     ${file}: 管理块已是最新`)
  } else if (current !== block) {
    readmeProblems.push(`${file} 管理块内容需要同步`)
  } else console.log(`ok     ${file}: 管理块已是最新`)
}

// ── 4. 汇总校验/写盘 ────────────────────────────────────────────────────────
if (write) {
  if (pkgOriginal !== pkgExpected) {
    await writeFile(pkgUrl, pkgExpected)
    console.log('write  package.json (engines.dsh + 6 dsh-* peers + cordis/schemastery)')
  } else console.log('ok     package.json')
  if (hasManifest) {
    if (manifestOriginal !== manifestExpected) {
      await writeFile(pluginJsonUrl, manifestExpected)
      console.log('write  dsh.plugin.json (engines.dsh + version)')
    } else console.log('ok     dsh.plugin.json')
  } else console.log('skip   dsh.plugin.json（本仓无 manifest）')
  console.log('done   --write 完成')
} else {
  const jsonDrift = pkgOriginal !== pkgExpected ? ['package.json (engines.dsh / peerDependencies)'] : []
  if (hasManifest && manifestOriginal !== manifestExpected) jsonDrift.push('dsh.plugin.json (engines.dsh / version)')
  if (jsonDrift.length === 0 && readmeProblems.length === 0) {
    console.log('ok     全部写点与 hosts.mjs 一致')
  } else {
    for (const p of [...jsonDrift, ...readmeProblems]) console.error(`drift  ${p}`)
    console.error('\n运行 node scripts/sync-hosts.mjs --write 修复')
    process.exit(1)
  }
}
